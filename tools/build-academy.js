// Converts the Academy course-production package into a script the app can load from file://.
// (A page opened from disk cannot fetch() neighbouring files, so the files are embedded as data.)
//   node tools/build-academy.js
// Reads academy/package/**  ->  writes academy/academy-files.js  (QG.academyFiles = {path: {type, size, text}})
var fs = require('fs'), path = require('path');
var root = path.join(__dirname, '..', 'academy'), pkg = path.join(root, 'package'), out = path.join(root, 'academy-files.js');
var TYPES = { '.ipynb': 'notebook', '.qs': 'qsharp', '.md': 'markdown', '.csv': 'csv', '.gift': 'gift', '.py': 'python', '.txt': 'text' };

function walk(dir, acc) {
  fs.readdirSync(dir).sort().forEach(function (f) {
    var p = path.join(dir, f), st = fs.statSync(p);
    if (st.isDirectory()) walk(p, acc); else acc.push(p);
  });
  return acc;
}

var files = {}, count = 0, bytes = 0;
walk(pkg, []).forEach(function (p) {
  var rel = path.relative(pkg, p).split(path.sep).join('/'), ext = path.extname(p).toLowerCase(), type = TYPES[ext];
  if (!type) { console.warn('skipped (unknown type):', rel); return; }
  var text = fs.readFileSync(p, 'utf8');
  if (type === 'notebook') JSON.parse(text); // fail loudly on a broken notebook
  files[rel] = { type: type, size: Buffer.byteLength(text), text: text };
  count++; bytes += Buffer.byteLength(text);
});

var js = '/* GENERATED by tools/build-academy.js from academy/package/. Do not edit by hand. */\n' +
  '(function (g) { var QG = g.QG || (g.QG = {}); QG.academyFiles = ' + JSON.stringify(files) + '; })(typeof self !== "undefined" ? self : globalThis);\n';
fs.writeFileSync(out, js);
console.log('academy-files.js: ' + count + ' files, ' + bytes + ' bytes of text');
